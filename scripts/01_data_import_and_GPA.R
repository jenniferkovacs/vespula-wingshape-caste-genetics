gdf <- geomorph.data.frame(
  coords    = Y.gpa$coords,
  Csize     = Y.gpa$Csize,
  Caste     = Y.gpa$caste,
  Colony    = Y.gpa$colony,
  Patriline = Y.gpa$patriline
)

# ---- 7. PCA on Procrustes-aligned shapes ------------------------------------
# Computed here once so all downstream scripts can use the same PCA object.

