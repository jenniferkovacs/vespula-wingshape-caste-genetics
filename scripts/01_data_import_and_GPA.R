variance_props <- (PCA$sdev^2 / sum(PCA$sdev^2)) * 100
cat(sprintf("\nPC1 explains %.2f%% of total shape variation\n", variance_props[1]))
cat(sprintf("PC2 explains %.2f%% of total shape variation\n", variance_props[2]))

