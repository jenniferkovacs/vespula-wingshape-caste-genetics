#          PCA    - gm.prcomp object for use in downstream scripts
#
# NOTE:    Males are haploid (develop from unfertilized eggs) and therefore
#          cannot be assigned to patrilines. Patriline-level genetic analyses
#          (heritability, G-matrix, distance models) are restricted to the
#          diploid female castes: workers and gynes.
